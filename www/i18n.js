let currentLang = 'ko';

function initI18n() {
  const saved = localStorage.getItem('boardvillage_lang');
  if (saved && BOARDVILLAGE_I18N[saved]) {
    currentLang = saved;
  } else {
    // Detect browser/device language
    const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (navLang.startsWith('en')) currentLang = 'en';
    else if (navLang.startsWith('ja')) currentLang = 'ja';
    else if (navLang.startsWith('zh')) currentLang = 'zh';
    else if (navLang.startsWith('de')) currentLang = 'de';
    else if (navLang.startsWith('es')) currentLang = 'es';
    else if (navLang.startsWith('fr')) currentLang = 'fr';
    else if (navLang.startsWith('vi')) currentLang = 'vi';
    else if (navLang.startsWith('th')) currentLang = 'th';
    else if (navLang.startsWith('id')) currentLang = 'id';
    else currentLang = 'ko';
  }
  applyTranslations();
  updateLangButtonUI();
}

function t(key, fallback = '') {
  const dict = BOARDVILLAGE_I18N[currentLang]?.dict || BOARDVILLAGE_I18N['ko'].dict;
  return dict[key] || BOARDVILLAGE_I18N['ko'].dict[key] || fallback || key;
}

function setLanguage(langCode) {
  if (!BOARDVILLAGE_I18N[langCode]) return;
  currentLang = langCode;
  localStorage.setItem('boardvillage_lang', langCode);
  applyTranslations();
  updateLangButtonUI();
  // Dispatch custom event for dynamic components
  window.dispatchEvent(new CustomEvent('boardvillage_lang_changed', { detail: { lang: currentLang } }));
}

function applyTranslations() {
  // 1. Elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val) el.innerHTML = val;
  });

  // 2. Placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (val) el.setAttribute('placeholder', val);
  });

  // 3. Titles / tooltips with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (val) el.setAttribute('title', val);
  });
}

function updateLangButtonUI() {
  const langData = BOARDVILLAGE_I18N[currentLang] || BOARDVILLAGE_I18N['ko'];
  const flagEl = document.getElementById('currentLangFlag');
  const nameEl = document.getElementById('currentLangName');
  if (flagEl) flagEl.textContent = langData.flag;
  if (nameEl) nameEl.textContent = langData.name;
}

function openLangModal() {
  const modal = document.getElementById('langModal');
  if (modal) modal.style.display = 'flex';
}

function closeLangModal() {
  const modal = document.getElementById('langModal');
  if (modal) modal.style.display = 'none';
}

// Expose globally
window.BV_I18N = {
  get current() { return currentLang; },
  t,
  setLanguage,
  init: initI18n,
  openModal: openLangModal,
  closeModal: closeLangModal,
  languages: BOARDVILLAGE_I18N
};

document.addEventListener('DOMContentLoaded', initI18n);
